function stripPinyinTones(str) {
  return str.toLowerCase()
    .replace(/[āáǎà]/g, "a")
    .replace(/[ēéěè]/g, "e")
    .replace(/[īíǐì]/g, "i")
    .replace(/[ōóǒò]/g, "o")
    .replace(/[ūúǔù]/g, "u")
    .replace(/[ǖǘǚǜü]/g, "u")
    .replace(/['’]/g, "");
}

function getSyllableCount(str) {
  const s = stripPinyinTones(str).replace(/[^\p{L}\d]/gu, "");
  if (!s) return 0;
  if (/^\d+$/.test(s)) return 1;

  let count = 0;
  let idx = 0;
  while (idx < s.length) {
    let matched = false;
    for (let len = Math.min(6, s.length - idx); len >= 1; len--) {
      const sub = s.substring(idx, idx + len);
      if (PINYIN_SYLLABLES.has(sub) || /^\d+$/.test(sub)) {
        count++;
        idx += len;
        matched = true;
        break;
      }
    }
    if (!matched) {
      idx++;
    }
  }
  return count;
}

function parseVocab(text) {
  const blocks = text.split(/\n\s*\n+/);
  const result = [];

  for (const block of blocks) {
    const lines = block.split("\n").map(l => l.trim()).filter(Boolean);
    if (lines.length === 0) continue;

    let word = lines[0].replace(/\s+/g, "");
    const isChinese = /[\u4e00-\u9fff\u3400-\u4dbf]/.test(word);
    if (!isChinese) continue;

    const hanziMatches = word.match(/[\u4e00-\u9fff\u3400-\u4dbf]|\d+/g) || [];
    const expectedSyllables = hanziMatches.length;

    let pinyin = "";
    let meaning = "";

    if (lines.length === 1) {
      pinyin = "";
      meaning = "";
    } else if (lines.length >= 3) {
      pinyin = lines[1];
      meaning = lines.slice(2).join(", ");
    } else {
      const line2 = lines[1];
      const tokens = line2.split(/\s+/);

      let currentSyllables = 0;
      let splitIdx = 0;

      for (let i = 0; i < tokens.length; i++) {
        const tok = tokens[i];
        const tokSyllables = getSyllableCount(tok);
        currentSyllables += tokSyllables;
        splitIdx = i + 1;
        if (currentSyllables >= expectedSyllables) {
          break;
        }
      }

      pinyin = tokens.slice(0, splitIdx).join(" ").trim();
      meaning = tokens.slice(splitIdx).join(" ").trim();
    }

    meaning = meaning.replace(/^['"‘“]+|['"’”]+$/g, "").trim();

    if (word === "下" && !meaning) meaning = "kế tiếp, xuống, phía dưới";
    if (word === "過" && !meaning) meaning = "qua";
    if (word === "又" && !meaning) meaning = "lại, vừa";
    if (word === "起來" && !meaning) meaning = "thức dậy, lên";
    if (word === "啦" && !meaning) meaning = "nhé, nha (trợ từ ngữ khí)";
    if (word === "林愛麗" && !meaning) meaning = "Lâm Ái Lệ";

    result.push({
      word,
      pinyin: pinyin || word,
      meaning: meaning || "Từ vựng tiếng Trung",
      level: "TOCFL A2",
      notes: ""
    });
  }

  return result;
}

