function parseVocab(text) {
  const blocks = text.split(/\n\s*\n+/);
  const result = [];
  const seen = new Set();

  for (const block of blocks) {
    const lines = block.split("\n").map(l => l.trim()).filter(Boolean);
    if (lines.length === 0) continue;

    const word = lines[0].trim();
    if (!word) continue;

    let pinyin = "";
    let meaning = "";

    // Validate if word contains at least one Chinese character
    const isChinese = /[\u4e00-\u9fff\u3400-\u4dbf]/.test(word);
    if (!isChinese) continue;

    if (lines.length === 1) {
      // Single line with word
    } else if (lines.length === 2) {
      const line2 = lines[1];
      const slashMatch = line2.match(/^([a-zA-ZāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜĀÁǍÀĒÉĚÈĪÍǏÌŌÓǑÒŪÚǓÙǕǗǙǛüÜ\s\/'’\-\(\)=0-9]+?)\s+([^\x00-\x7F].*)$/u);
      if (slashMatch) {
        pinyin = slashMatch[1].replace(/\/\s*/g, " / ").replace(/\s+/g, " ").trim();
        meaning = slashMatch[2].trim();
      } else {
        const match = line2.match(/^([a-zA-ZāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜĀÁǍÀĒÉĚÈĪÍǏÌŌÓǑÒŪÚǓÙǕǗǙǛüÜ\s\/'’\-\(\)=0-9]+?)\s+([\p{L}\p{M}\p{P}\s\d]+)$/u);
        if (match) {
          pinyin = match[1].replace(/\/\s*/g, " / ").replace(/\s+/g, " ").trim();
          meaning = match[2].trim();
        } else {
          const hasToneOrAscii = /^[a-zA-ZāáǎàēéěèīíǐìōóǒòūúǔùǖǘǚǜĀÁǍÀĒÉĚÈĪÍǏÌŌÓǑÒŪÚǓÙǕǗǙǛüÜ\s\/'’\-\(\)=0-9]+$/.test(line2);
          if (hasToneOrAscii) {
            pinyin = line2.replace(/\/\s*/g, " / ").replace(/\s+/g, " ").trim();
            meaning = "";
          } else {
            pinyin = "";
            meaning = line2;
          }
        }
      }
    } else if (lines.length >= 3) {
      pinyin = lines[1].replace(/\/\s*/g, " / ").replace(/\s+/g, " ").trim();
      meaning = lines.slice(2).join(", ");
    }

    // Clean word: remove parentheses note like "臺灣 (=台灣)" -> word: "臺灣", notes: "台灣"
    let cleanWord = word;
    let notes = "";
    if (cleanWord.includes("(=台灣)") || cleanWord.includes("(＝台灣)")) {
      cleanWord = "臺灣";
      notes = "Dạng giản thể/dị thể: 台灣";
    }

    // Check duplicate
    const key = cleanWord + "|" + meaning;
    if (seen.has(key)) continue;
    seen.add(key);

    result.push({
      word: cleanWord,
      pinyin: pinyin || cleanWord,
      meaning: meaning || "Từ vựng tiếng Trung",
      level: "TOCFL A1",
      notes: notes
    });
  }

  return result;
}

